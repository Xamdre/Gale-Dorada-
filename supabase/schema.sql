create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  role text not null default 'customer' check (role in ('customer','admin')),
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'name',''))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists(select 1 from public.profiles where id = (select auth.uid()) and role = 'admin');
$$;

create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  slug text not null unique,
  description text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  category text not null default 'General',
  category_id uuid references public.categories(id) on delete set null,
  sku text unique,
  short_description text,
  description text not null default '',
  price_cop bigint not null check (price_cop >= 0),
  compare_at_price_cop bigint check (compare_at_price_cop is null or compare_at_price_cop >= 0),
  stock integer not null default 0 check (stock >= 0),
  image_url text,
  active boolean not null default false,
  featured boolean not null default false,
  status text not null default 'draft' check (status in ('draft','published','archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.products add column if not exists category text not null default 'General';
alter table public.products add column if not exists image_url text;
alter table public.products add column if not exists active boolean not null default false;
alter table public.products add column if not exists featured boolean not null default false;
alter table public.products add column if not exists status text not null default 'draft';

create table if not exists public.product_images (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id) on delete cascade,
  storage_path text not null,
  alt_text text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique(product_id, storage_path)
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_first_name text not null,
  customer_last_name text not null default '',
  customer_phone text not null,
  delivery_address text not null,
  delivery_city text not null,
  total_cop bigint not null check(total_cop >= 0),
  status text not null default 'pending_payment' check(status in ('pending_payment','paid','preparing','shipped','delivered','cancelled','refunded')),
  payment_status text not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null check(quantity > 0),
  unit_price_cop bigint not null check(unit_price_cop >= 0),
  created_at timestamptz not null default now()
);

create index if not exists products_active_created_idx on public.products(active, created_at desc);
create index if not exists products_category_idx on public.products(category_id);
create index if not exists product_images_product_sort_idx on public.product_images(product_id, sort_order);
create index if not exists orders_created_idx on public.orders(created_at desc);

create or replace function public.set_updated_at()
returns trigger language plpgsql set search_path = ''
as $$ begin new.updated_at = now(); return new; end; $$;

create or replace function public.sync_product_status()
returns trigger language plpgsql set search_path = ''
as $$
begin
  if new.status = 'archived' then new.active := false;
  else new.status := case when new.active then 'published' else 'draft' end;
  end if;
  return new;
end;
$$;

drop trigger if exists products_sync_status on public.products;
create trigger products_sync_status before insert or update on public.products
for each row execute procedure public.sync_product_status();

drop trigger if exists categories_updated_at on public.categories;
create trigger categories_updated_at before update on public.categories
for each row execute procedure public.set_updated_at();
drop trigger if exists products_updated_at on public.products;
create trigger products_updated_at before update on public.products
for each row execute procedure public.set_updated_at();
drop trigger if exists orders_updated_at on public.orders;
create trigger orders_updated_at before update on public.orders
for each row execute procedure public.set_updated_at();

