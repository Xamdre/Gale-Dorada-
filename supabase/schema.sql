drop policy if exists "Users read own profile" on public.profiles;
create policy "Users read own profile" on public.profiles for select to authenticated
using (id = (select auth.uid()) or (select public.is_admin()));
drop policy if exists "Admins manage profiles" on public.profiles;
create policy "Admins manage profiles" on public.profiles for all to authenticated
using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "Public read active categories" on public.categories;
create policy "Public read active categories" on public.categories for select to anon, authenticated
using (is_active or (select public.is_admin()));
drop policy if exists "Admins manage categories" on public.categories;
create policy "Admins manage categories" on public.categories for all to authenticated
using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "Public read published products" on public.products;
create policy "Public read published products" on public.products for select to anon, authenticated
using (active or (select public.is_admin()));
drop policy if exists "Admins manage products" on public.products;
create policy "Admins manage products" on public.products for all to authenticated
using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "Public read images of published products" on public.product_images;
create policy "Public read images of published products" on public.product_images for select to anon, authenticated
using (exists(select 1 from public.products p where p.id = product_id and (p.active or (select public.is_admin()))));
drop policy if exists "Admins manage product images" on public.product_images;
create policy "Admins manage product images" on public.product_images for all to authenticated
using ((select public.is_admin())) with check ((select public.is_admin()));

drop policy if exists "Admins manage orders" on public.orders;
create policy "Admins manage orders" on public.orders for all to authenticated
using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists "Admins manage order items" on public.order_items;
create policy "Admins manage order items" on public.order_items for all to authenticated
using ((select public.is_admin())) with check ((select public.is_admin()));

insert into storage.buckets(id,name,public)
values('product-images','product-images',true)
on conflict(id) do update set public = true;

drop policy if exists "Public view product images" on storage.objects;
create policy "Public view product images" on storage.objects for select to anon, authenticated
using(bucket_id = 'product-images');
drop policy if exists "Admins upload product images" on storage.objects;
create policy "Admins upload product images" on storage.objects for insert to authenticated
with check(bucket_id = 'product-images' and (select public.is_admin()));
drop policy if exists "Admins update product images" on storage.objects;
create policy "Admins update product images" on storage.objects for update to authenticated
using(bucket_id = 'product-images' and (select public.is_admin()))
with check(bucket_id = 'product-images' and (select public.is_admin()));
drop policy if exists "Admins delete product images" on storage.objects;
create policy "Admins delete product images" on storage.objects for delete to authenticated
using(bucket_id = 'product-images' and (select public.is_admin()));

